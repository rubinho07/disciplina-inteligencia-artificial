def validar_cpf(cpf):
    cpf = "".join(caractere for caractere in cpf if caractere.isdigit())

    if len(cpf) != 11:
        return False

    if cpf == cpf[0] * 11:
        return False

    soma = 0

    for indice in range(9):
        soma += int(cpf[indice]) * (10 - indice)

    resto = soma % 11

    if resto < 2:
        primeiro_digito = 0
    else:
        primeiro_digito = 11 - resto

    soma = 0

    for indice in range(10):
        soma += int(cpf[indice]) * (11 - indice)

    resto = soma % 11

    if resto < 2:
        segundo_digito = 0
    else:
        segundo_digito = 11 - resto

    return (
        primeiro_digito == int(cpf[9])
        and segundo_digito == int(cpf[10])
    )


