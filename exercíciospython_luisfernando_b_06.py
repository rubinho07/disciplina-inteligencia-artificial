def criptografar(mensagem, deslocamento):
    mensagem_cifrada = ""

    for caractere in mensagem:
        if caractere.isalpha():
            if caractere.isupper():
                codigo_inicial = ord("A")
            else:
                codigo_inicial = ord("a")

            posicao = ord(caractere) - codigo_inicial
            nova_posicao = (posicao + deslocamento) % 26
            nova_letra = chr(codigo_inicial + nova_posicao)

            mensagem_cifrada += nova_letra
        else:
            mensagem_cifrada += caractere

    return mensagem_cifrada


