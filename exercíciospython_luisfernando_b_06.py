"""Exercicio 21 - A busca binaria procura um elemento em uma lista ordenada, com isso dividindo a área de busca pela metade a cada repetição ."""

def busca_binaria(lista, elemento):
    inicio = 0
    fim = len(lista) - 1

    while inicio <= fim:
        meio = (inicio + fim) // 2

        if lista[meio] == elemento:
            return meio
        elif lista[meio] < elemento:
            inicio = meio + 1
        else:
            fim = meio - 1

    return -1


